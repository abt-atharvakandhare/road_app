import 'package:bloc_test/bloc_test.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:mocktail/mocktail.dart';
import 'package:road_mobile/data/model/login/login_response_model.dart';
import 'package:road_mobile/data/model/login/mfa_method.dart';
import 'package:road_mobile/data/model/provider/provider_response_model.dart';
import 'package:road_mobile/flavors.dart';
import 'package:road_mobile/l10n/app_localizations.dart';
import 'package:road_mobile/ui/onboarding/login/cubit/auth_cubit.dart';
import 'package:road_mobile/ui/onboarding/login/mfa_code_entry_widget.dart';
import 'package:road_mobile/ui/utils/widgets/mfa_code_entry_card.dart';
import 'package:sms_autofill/sms_autofill.dart';

class MockAuthCubit extends MockCubit<AuthState> implements AuthCubit {}

void main() {
  late MockAuthCubit mockAuthCubit;

  final providerModel = ProviderResponseModel(id: 'test-provider');

  // The SMS steps start the retriever listener (tests run as Android), so the
  // sms_autofill channel needs a handler for the widget's outgoing calls.
  const smsChannel = MethodChannel('sms_autofill');

  setUpAll(() {
    F.appFlavor = Flavor.eflux;
  });

  setUp(() {
    TestWidgetsFlutterBinding.ensureInitialized();
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(smsChannel, (call) async => null);
    mockAuthCubit = MockAuthCubit();
    whenListen(mockAuthCubit, const Stream<AuthState>.empty(),
        initialState: const AuthState.loggedOut());
    when(() => mockAuthCubit.passkeySupported).thenReturn(false);
  });

  tearDown(() {
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger.setMockMethodCallHandler(smsChannel, null);
  });

  Widget buildTestWidget(TwoFactorAuth twoFactorAuth) {
    return MaterialApp(
      localizationsDelegates: AppLocalizations.localizationsDelegates,
      supportedLocales: AppLocalizations.supportedLocales,
      locale: AppLocalizations.supportedLocales.first,
      home: Scaffold(
        body: SingleChildScrollView(
          child: BlocProvider<AuthCubit>.value(
            value: mockAuthCubit,
            child: MfaCodeEntryWidget(twoFactorAuth: twoFactorAuth),
          ),
        ),
      ),
    );
  }

  TwoFactorAuth pendingSms({List<MfaMethod> methods = const [MfaMethod.sms], bool? canUseRecoveryCode}) {
    return TwoFactorAuth.pendingSms(
      challenge: MfaPendingChallengeModel(
          pendingId: 'pending-1', methods: methods, canUseRecoveryCode: canUseRecoveryCode),
      hint: '•••• 3813',
      email: 'ray@example.com',
      providerModel: providerModel,
    );
  }

  testWidgets('the SMS step keeps its header, resend link and footer links around the shared card',
      (tester) async {
    await tester.pumpWidget(buildTestWidget(
        pendingSms(methods: const [MfaMethod.sms, MfaMethod.totp], canUseRecoveryCode: true)));

    expect(find.textContaining('We sent a verification code to •••• 3813.'), findsOneWidget);
    expect(find.textContaining("Didn't receive the code?"), findsOneWidget);
    expect(find.text('Use a different verification method'), findsOneWidget);
    expect(find.textContaining('Use a recovery code'), findsOneWidget);

    final card = tester.widget<MfaCodeEntryCard>(find.byType(MfaCodeEntryCard));
    expect(card.smsAutofill, isTrue);
    expect(card.onResend, isNotNull);
  });

  testWidgets('a single-method SMS step without recovery codes shows no footer links', (tester) async {
    await tester.pumpWidget(buildTestWidget(pendingSms()));

    expect(find.text('Use a different verification method'), findsNothing);
    expect(find.textContaining('Use a recovery code'), findsNothing);
  });

  testWidgets('the TOTP step hides the resend affordance and disables SMS autofill', (tester) async {
    await tester.pumpWidget(buildTestWidget(TwoFactorAuth.pendingTotp(
      challenge: MfaPendingChallengeModel(pendingId: 'pending-1', methods: const [MfaMethod.totp]),
      email: 'ray@example.com',
      providerModel: providerModel,
    )));

    expect(find.text('Enter the security code generated by the app.'), findsOneWidget);
    expect(find.textContaining("Didn't receive the code?"), findsNothing);

    final card = tester.widget<MfaCodeEntryCard>(find.byType(MfaCodeEntryCard));
    expect(card.smsAutofill, isFalse);
    expect(card.onResend, isNull);
  });

  testWidgets('six digits submit to the pending-challenge verify', (tester) async {
    when(() => mockAuthCubit.verifyPendingMfaCode('123456'))
        .thenAnswer((_) async => TwoFactorAuthResult.wrongCode);

    await tester.pumpWidget(buildTestWidget(pendingSms()));
    await tester.enterText(find.byType(PinInputTextField), '123456');
    await tester.pump();

    verify(() => mockAuthCubit.verifyPendingMfaCode('123456')).called(1);
    expect(find.textContaining('Code entered is incorrect.'), findsOneWidget);
  });

  testWidgets('the enrolment email proof submits to the enrolment verify', (tester) async {
    when(() => mockAuthCubit.verifyEnrolmentEmailProof('654321'))
        .thenAnswer((_) async => TwoFactorAuthResult.success);

    await tester.pumpWidget(buildTestWidget(TwoFactorAuth.enrolEmailProof(
      enrolment: MfaEnrolmentModel(
          enrolId: 'enrol-1', mode: MfaMode.encourage, permittedMethods: const [MfaMethod.totp]),
      email: 'ray@example.com',
      providerModel: providerModel,
    )));

    expect(find.textContaining('ray@example.com'), findsOneWidget);

    await tester.enterText(find.byType(PinInputTextField), '654321');
    await tester.pump();

    verify(() => mockAuthCubit.verifyEnrolmentEmailProof('654321')).called(1);
  });
}
